test('starts a three-day food history directly and keeps parent notes with a meal', async ({page}) => {
 await page.goto('/?demo=1')
 await page.evaluate(() => localStorage.setItem('mealtrace:clients', JSON.stringify([{id:'c', firstName:'Example child', code:'TEST', dob:'2024-01-01', sex:'F', feeding:'na', context:'', createdAt:1, updatedAt:1}])))
 await page.goto('/?demo=1#/c/c')
 await page.reload()
 await expect(page.getByRole('heading',{name:'Example child'})).toBeVisible()
 await page.getByRole('button',{name:'Add food history'}).first().click()
 await expect(page.getByLabel('Food history format')).toHaveValue('diary')
 await expect(page.getByRole('button',{name:/^Day 3/})).toBeVisible()
 await page.getByLabel('Food history format').selectOption('typical')
 await expect(page.getByRole('heading',{name:'Typical day'})).toBeVisible()
 await page.getByText('Family notes',{exact:true}).first().click()
 await page.getByLabel('Family notes for Breakfast').fill('Offered fruit, some refused.')
 await expect(page.getByLabel('Food history format')).toBeDisabled()
 await expect(page.getByText('Saved in this browser only')).toBeVisible()
 await page.reload()
 await page.getByText('Family notes · added').click()
 await expect(page.getByLabel('Family notes for Breakfast')).toHaveValue('Offered fruit, some refused.')
})

test('copies a CoFID food with its nutrients and adds a measured recipe with servings', async ({page}) => {
 await page.goto('/?demo=1#/foods')
 await page.getByPlaceholder(/Search 2,887 foods/).fill('12-596')
 await page.getByRole('button',{name:/Milk, whole, pasteurised, average/}).click()
 await page.getByRole('button',{name:'Copy and edit'}).click()
 await expect(page.getByRole('heading',{name:'Create a CoFID food variant'})).toBeVisible()
 await expect(page.getByLabel('Energy per 100 g')).toHaveValue('63')
 await page.getByRole('button',{name:'Cancel'}).click()
 await page.getByRole('link',{name:'Build a recipe'}).click()
 await page.getByLabel('Recipe name').fill('Synthetic milk recipe')
 await page.getByRole('combobox',{name:'Search for an ingredient…'}).fill('12-596')
 await page.getByRole('combobox',{name:'Search for an ingredient…'}).press('Enter')
 await page.getByLabel(/Amount of Milk, whole/).fill('200')
 await page.getByLabel('Finished weight (g)').fill('200')
 await page.getByLabel('Number of servings').fill('2')
 await expect(page.getByRole('row',{name:/Energy.*126 kcal.*63 kcal/})).toBeVisible()
 await page.getByRole('button',{name:'Save recipe to Food library'}).click()
 await expect(page.getByText(/Recipe saved/)).toBeVisible()
 await page.getByRole('link',{name:'Back to Food library'}).click()
 await page.getByRole('tab',{name:/Recipes/}).click()
 await page.getByRole('link',{name:'Edit recipe'}).click()
 await expect(page.getByLabel('Number of servings')).toHaveValue('2')
})
