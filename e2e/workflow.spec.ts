import { test, expect } from '@playwright/test'
test('synthetic record entry, completion and family privacy',async ({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?demo=1')
 await page.evaluate(()=>{
  localStorage.setItem('mealtrace:clients',JSON.stringify([{id:'a',firstName:'Synthetic Alice',code:'TEST-A',dob:'2024-01-01',sex:'F',feeding:'na',context:'PRIVATE CONTEXT',createdAt:1,updatedAt:1},{id:'b',firstName:'Synthetic Bob',code:'TEST-B',dob:'2024-01-01',sex:'M',feeding:'na',context:'',createdAt:1,updatedAt:1}]))
  localStorage.setItem('mealtrace:assessments',JSON.stringify([{id:'assessment',clientId:'a',date:'2026-11-15',type:'typical',title:'Synthetic diary',createdAt:1,updatedAt:1,days:[{id:'day',label:'Typical day',meals:[{id:'breakfast',name:'Breakfast',items:[{id:'milk',foodId:'c:12-596',name:'Whole milk',amount:200,qty:200,unit:'g',measure:'g',measureAmount:1}]}]}]}]))
 })
 await page.goto('/?demo=1#/c/a/a/assessment');await page.reload()
 const search = page.getByRole('combobox', {name:'Add to breakfast…'})
 await search.click()
 await expect(page.getByRole('option',{name:'Show more foods'})).toBeVisible()
 await search.fill('12-596')
 await expect(page.getByRole('option',{name:/Milk, whole, pasteurised, average/})).toBeVisible()
 await search.press('Escape')
 await page.getByPlaceholder('Who reported it, how typical the days were, anything that affects interpretation…').fill('Private session observations')
 await page.getByRole('button',{name:'2. Review intake'}).click()
 await expect(page.getByRole('button',{name:'Finalise and enable PDFs'})).toBeDisabled()
 await expect(page.getByText('Mark each day complete below', {exact:false})).toBeVisible()
 await page.getByRole('button',{name:'Preview parent summary'}).click()
 await expect(page.getByText('No completed days to show yet.')).toBeVisible()
 await expect(page.getByRole('button',{name:'Download PDF for Drive'})).toHaveCount(0)
 await page.getByRole('link',{name:'Back to assessment'}).click()
 await page.getByRole('button',{name:'2. Review intake'}).click()
 await page.getByLabel('Typical day complete').check()
 await expect(page.getByText('Draft assessment · 1 completed days')).toBeVisible()
 await page.getByLabel('Agreed actions and follow-up (shared with parents)').fill('Agreed synthetic action')
 await expect(page.getByText('Saved in this browser only')).toBeVisible()
 page.on('dialog',d=>d.accept())
 await page.getByRole('button',{name:'Finalise and enable PDFs'}).click()
 await expect(page.getByText('Finalised record — read only')).toBeVisible()
 await page.getByRole('button',{name:'Parent summary'}).click()
 const [download] = await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download PDF for Drive'}).click()])
 expect(download.suggestedFilename()).toBe('TEST-A-2026-11-15-parent-assessment.pdf')
 await page.goto('/?demo=1#/c/a/family/assessment')
 await expect(page.getByRole('heading',{name:'Synthetic Alice’s feeding plan'})).toBeVisible()
 await expect(page.getByText('Agreed synthetic action')).toBeVisible()
 await expect(page.getByText('PRIVATE CONTEXT')).toHaveCount(0)
 await expect(page.getByText('Synthetic Bob')).toHaveCount(0)
 await expect(page.getByText('Private session observations')).toHaveCount(0)
 expect(errors).toEqual([])
 await page.screenshot({path:'test-results/family-view.png'})
})
test('context stays with originating child after immediate navigation',async ({page})=>{
 await page.goto('/?demo=1');await page.evaluate(()=>localStorage.setItem('mealtrace:clients',JSON.stringify(['a','b'].map(id=>({id,firstName:id,code:id,dob:'2024-01-01',sex:'F',feeding:'na',context:'',createdAt:1,updatedAt:1})))));await page.goto('/?demo=1#/c/a');await page.reload()
 await page.getByPlaceholder('Allergies, feeding concerns, medication or goals…').fill('Only child A')
 await page.getByRole('button',{name:'Save context'}).click()
 await expect(page.getByText('Context saved.')).toBeVisible()
 await page.goto('/?demo=1#/c/b')
 await expect(page.getByPlaceholder('Allergies, feeding concerns, medication or goals…')).toHaveValue('')
 const clients=await page.evaluate(()=>JSON.parse(localStorage.getItem('mealtrace:clients')!));expect(clients.find((c:any)=>c.id==='a').context).toBe('Only child A');expect(clients.find((c:any)=>c.id==='b').context).toBe('')
})
