import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function pick(page: Page, search: string, name: RegExp) {
  const input = page.getByRole('combobox', { name: /^Add (a food|an ingredient|to )/ })
  await input.fill(search)
  await page.getByRole('option', { name }).first().click()
}

test('explores portions, charts and source exports without creating client records', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?demo=1#/explorer')
  await expect(page.getByRole('heading', { name: 'Nutrient Explorer', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Export analysis' })).toBeDisabled()
  await pick(page, 'banana', /Bananas, flesh only/)
  const amount = page.getByLabel('Quantity of Bananas, flesh only', { exact: true })
  await expect(amount).toHaveValue('100')
  const energy = page.getByTestId('explorer-energy')
  const whole = Number((await energy.innerText()).replaceAll(',', ''))
  expect(whole).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Halve Bananas, flesh only', exact: true }).click()
  await expect(amount).toHaveValue('50')
  expect(Number(await energy.innerText())).toBe(Math.round(whole / 2))
  await page.getByRole('radiogroup', { name: 'Analysis basis' }).getByRole('radio', { name: /^Per 100 g/ }).click()
  await expect(energy).toHaveText(String(whole))
  await page.getByRole('button', { name: 'Chart Potassium', exact: true }).click()
  await expect(page.getByRole('list', { name: 'Potassium contributions' })).toContainText('Bananas, flesh only')
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export analysis' }).click()])
  const csv = await readFile(await download.path(), 'utf8')
  expect(csv).toContain('Per 100 g')
  expect(csv).toContain('UK CoFID 2021')
  expect(csv).toContain('Source value')
  expect(csv).toContain('Bananas, flesh only')
  await page.getByRole('link', { name: 'All clients', exact: true }).click()
  await page.getByRole('link', { name: 'Nutrient Explorer', exact: true }).click()
  await expect(amount).toHaveValue('50')
  await page.getByText('Sources & calculation notes', { exact: false }).click()
  await expect(page.getByRole('link', { name: /dataset & user guide/ })).toHaveAttribute('href', /gov.uk/)
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.locator('main').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: 'test-results/explorer-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

test('builds a recipe, scales its yield and saves a usable library recipe', async ({ page }) => {
  await page.goto('/?demo=1#/explorer')
  await page.getByRole('button', { name: 'Recipe', exact: true }).click()
  await page.getByLabel('Exploration title').fill('Synthetic banana recipe')
  await pick(page, 'banana', /Bananas, flesh only/)
  const energy = Number(await page.getByTestId('explorer-energy').innerText())
  await page.getByLabel('Number of portions', { exact: true }).fill('2')
  await page.getByLabel('Finished weight (g)', { exact: true }).fill('80')
  await page.getByRole('radiogroup', { name: 'Analysis basis' }).getByRole('radio', { name: /^Per portion/ }).click()
  expect(Number(await page.getByTestId('explorer-energy').innerText())).toBe(Math.round(energy / 2))
  await page.getByRole('radiogroup', { name: 'Analysis basis' }).getByRole('radio', { name: /^Per 100 g/ }).click()
  expect(Number(await page.getByTestId('explorer-energy').innerText())).toBe(Math.round(energy / 0.8))
  await page.getByRole('button', { name: 'Save as library recipe' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Recipe name')).toHaveValue('Synthetic banana recipe')
  await dialog.getByRole('button', { name: 'Save recipe', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Recipe saved to your library')
  await page.getByRole('button', { name: 'Foods', exact: true }).click()
  await expect(page.getByTestId('explorer-entry')).toHaveCount(0)
  // a saved recipe is added as its ingredients, one portion's worth
  await pick(page, 'Synthetic banana recipe', /Synthetic banana recipe/)
  await expect(page.getByTestId('explorer-entry')).toHaveCount(1)
  await expect(page.getByTestId('explorer-entry')).toContainText('from Synthetic banana recipe')
  await expect(page.getByLabel('Quantity of Bananas, flesh only', { exact: true })).toHaveValue('50')
  expect(Number(await page.getByTestId('explorer-energy').innerText())).toBe(Math.round(energy / 2))
})

test('opens a saved recipe from the library, broken down by ingredient', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?demo=1#/explorer')
  await page.getByRole('button', { name: 'Recipe', exact: true }).click()
  await page.getByLabel('Exploration title').fill('Synthetic porridge')
  await pick(page, 'porridge oats', /Porridge oats, unfortified/)
  await page.getByLabel('Quantity of Porridge oats, unfortified', { exact: true }).fill('80')
  await pick(page, '12-596', /Milk, whole, pasteurised, average/)
  await page.getByLabel('Quantity of Milk, whole, pasteurised, average', { exact: true }).fill('300')
  await page.getByLabel('Number of portions', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Save as library recipe' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Save recipe', exact: true }).click()

  // library: per-portion summary and a direct route to the full analysis
  await page.goto('/?demo=1#/foods')
  await page.getByLabel('Search the food library').fill('Synthetic porridge')
  await page.getByRole('button', { name: /^Synthetic porridge/ }).first().click()
  await expect(page.getByText('Per portion', { exact: true })).toBeVisible()
  // each ingredient shows its amount per portion as well as for the whole recipe
  await expect(page.getByTestId('ingredient-per-portion')).toHaveText(['40 g', '150 g'])
  await page.getByRole('button', { name: 'See which ingredients provide each nutrient' }).click()

  // explorer: recipe tab, ingredients listed separately, per portion
  await expect(page.getByLabel('Exploration title')).toHaveValue('Synthetic porridge')
  await expect(page.getByTestId('explorer-entry')).toHaveCount(2)
  await expect(page.getByRole('radiogroup', { name: 'Analysis basis' }).getByRole('radio', { name: /^Per portion/ })).toHaveAttribute('aria-checked', 'true')
  // the basis switch and the breakdown stay on screen however far the page is scrolled
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.locator('main').evaluate((m) => m.scrollTo(0, m.scrollHeight))
  await expect(page.getByRole('radiogroup', { name: 'Analysis basis' })).toBeInViewport()
  await expect(page.getByRole('list', { name: /contributions$/ })).toBeInViewport()
  await page.getByRole('button', { name: 'Chart Iron', exact: true }).click()
  const iron = page.getByRole('list', { name: 'Iron contributions' })
  await expect(iron.getByRole('listitem')).toHaveCount(2)
  await expect(iron).toContainText('Porridge oats, unfortified')
  await expect(iron).toContainText('%')
  // how much of each ingredient is in one portion, next to what it provides
  await expect(iron.getByRole('listitem').filter({ hasText: 'Porridge oats' }).getByTestId('explorer-contribution-amount')).toHaveText('40 g per portion')
  await expect(page.getByText('40 g per portion', { exact: false }).first()).toBeVisible()

  // switching measure keeps the amount
  const milkQty = page.getByLabel('Quantity of Milk, whole, pasteurised, average', { exact: true })
  const energy = await page.getByTestId('explorer-energy').innerText()
  await page.getByLabel('Measure for Milk, whole, pasteurised, average').selectOption('cup (200 ml)')
  await expect(milkQty).toHaveValue('1.456')
  await expect(page.getByTestId('explorer-energy')).toHaveText(energy)
  expect(errors).toEqual([])
})

